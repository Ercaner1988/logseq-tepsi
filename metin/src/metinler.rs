/// `m`nin `dil` dilindeki şablonu (yer tutucular `{}`; doldurmak için `bicim`).
pub fn metin(dil: Dil, m: Metin) -> &'static str {
    match dil {
        Dil::Tr => tr(m),
        Dil::En => en(m),
    }
}

